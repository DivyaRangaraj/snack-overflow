export function getSnackSlug(name: string): string {
  if (SNACK_SLUGS[name]) return SNACK_SLUGS[name];
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

export function getSnackImagePath(name: string): string {
  const slug = getSnackSlug(name);
  return `/snacks/${slug}.svg`;
}

